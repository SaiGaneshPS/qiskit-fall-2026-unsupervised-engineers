"""Writes demo/data.js for the interactive demo (demo/index.html).

Blackout hours of a plan are exactly linear in the Labrador-Island Link outage rate q (the link is one unit,
so P(shortfall) = P(short | link up) + q * [P(short | link down) - P(short | link up)] in every hour). The E7
table scores all 4,096 plans at q = 1.1%, 3% and 5%; we store the line a + b*q for each plan, which reproduces
the engine at any q (checked against experiments/turbine_decision.py to the third decimal), plus each plan's
cost parts, which do not depend on q.
"""
import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]


def main():
    t = pd.read_csv(ROOT / "results" / "e7_plan_table.csv")
    w = t.pivot(index="idx", columns="scenario", values="lolh").sort_index()
    l1, l3, l5 = w["1pct"].values, w["3pct"].values, w["5pct"].values
    b = (l5 - l1) / (0.05 - 0.011)
    a = l1 - b * 0.011
    assert np.abs(a + b * 0.03 - l3).max() < 1e-6
    one = t[t.scenario == "1pct"].sort_values("idx")
    plans = dict(a=np.round(a, 5).tolist(), b=np.round(b, 4).tolist(),
                 build=np.round(one.capex + one.opex, 3).tolist(), wind=np.round(one.wind_value, 3).tolist(),
                 bills=np.round(one.household_savings, 3).tolist(), co2=np.round(one.co2_kt, 2).tolist(),
                 carbon=np.round(one.carbon_cost, 3).tolist())
    e5 = json.loads((ROOT / "results" / "e5_hardware_scale_noise.json").read_text())
    hw = json.loads((ROOT / "results" / "e5_hardware.json").read_text())
    tw = json.loads((ROOT / "results" / "e5_hardware_twin.json").read_text())
    per_home = json.loads((ROOT / "results" / "e7_per_home.json").read_text())["per_home"]
    data = dict(
        plans=plans,
        circuit=dict(case=e5["instance"], p=e5["p_true"], reduction=e5["reduction"],
                     run1=hw["hardware"]["measured"][:5], run2=tw["corrected_target"], jobs=[hw["hardware"]["job_id"], tw["job_id"]]),
        per_home=per_home,
    )
    cs = ROOT / "results" / "coldsnap_plans.json"
    if cs.exists():
        c = json.loads(cs.read_text())
        data["coldsnap"] = dict(safe=c["safe"], runs=c["cases"][0]["runs"], cases=[
            {k: v[k] for k in ("plan", "link", "p_exact", "qae_mean", "qae_sd", "mc_sd", "truth", "qae_calls", "mc_calls",
                                "n_mc_needed", "n_qae_needed", "qubits", "cx")} for v in c["cases"]])
    out = ROOT / "demo" / "data.js"
    out.parent.mkdir(exist_ok=True)
    out.write_text("// generated by tools/export_demo_data.py from results/\nconst DATA = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print("wrote", out, out.stat().st_size // 1024, "KB")


if __name__ == "__main__":
    main()
